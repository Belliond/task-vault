-- =========================================================
--  DARI MIGRASI: 20261101000000_baseline_tasks.sql
-- =========================================================

-- =========================================================
--  BASELINE: tabel public.tasks + mode akses bersama
--
--  Migrasi ini aman untuk dua kondisi:
--    1. Proyek baru  -> tabel dibuat dari nol.
--    2. Proyek lama  -> tabel sudah ada, perintah dilewati
--                       (create table if not exists).
-- =========================================================

create table if not exists public.tasks (

    id          bigint generated by default as identity primary key,

    course      text        not null,
    class_name  text        not null,
    deadline    date        not null,
    category    text        not null,

    -- Tiga nilai baku. Versi lama memakai istilah Indonesia
    -- ("Belum Dikerjakan", dst.); migrasi berikutnya
    -- menormalkan data lama ke kosakata ini.
    status      text        not null default 'Pending',

    created_at  timestamptz not null default now()

);


-- =========================================================
--  MODE BERSAMA / TANPA LOGIN
--
--  RLS dimatikan secara sadar: siapa pun yang membuka web
--  boleh baca/tulis/hapus. Policy lama dihapus lebih dulu
--  supaya tidak membingungkan bila suatu saat RLS
--  diaktifkan lagi.
--
--  Konsekuensi yang perlu disadari: publishable key ada di
--  script.js dan terkirim ke browser, jadi siapa pun yang
--  menemukan URL + key bisa mengubah isi tabel ini.
-- =========================================================

alter table public.tasks disable row level security;

drop policy if exists "read own tasks" on public.tasks;
drop policy if exists "insert own tasks" on public.tasks;
drop policy if exists "update own tasks" on public.tasks;
drop policy if exists "delete own tasks" on public.tasks;
drop policy if exists "Enable read access for all users" on public.tasks;
drop policy if exists "Allow public insert" on public.tasks;
drop policy if exists "Allow anon update tasks" on public.tasks;
drop policy if exists "Allow public delete" on public.tasks;

-- Kolom user_id adalah sisa era login dan tidak dipakai lagi.
alter table public.tasks drop column if exists user_id;


-- =========================================================
--  DARI MIGRASI: 20261102000000_lms_sync_columns.sql
-- =========================================================

-- =========================================================
--  KOLOM PENDUKUNG SINKRONISASI LMS (MOODLE / CLASSROOM)
-- =========================================================

alter table public.tasks
    add column if not exists source text not null default 'manual',
    add column if not exists external_id text,
    add column if not exists synced_at timestamptz;

-- Tugas hasil sync yang "dihapus" user tidak benar-benar
-- dibuang. Sync berikutnya mencari baris berdasarkan
-- external_id; kalau barisnya hilang, tugas akan di-insert
-- ulang sehingga tombol DELETE tampak tidak berfungsi.
-- Karena itu baris hanya ditandai di sini lalu
-- disembunyikan dari daftar.
alter table public.tasks
    add column if not exists dismissed_at timestamptz;


-- =========================================================
--  ANTI-DOBEL
--  Sync yang berjalan berkali-kali (atau dari dua browser
--  sekaligus) tidak boleh menggandakan tugas. Index unik
--  parsial hanya berlaku untuk baris yang punya
--  external_id, sehingga tugas manual tidak terpengaruh.
-- =========================================================

drop index if exists tasks_user_id_idx;
drop index if exists tasks_user_source_external_idx;

create unique index if not exists tasks_source_external_idx
    on public.tasks (source, external_id)
    where external_id is not null;


-- Mempercepat query daftar (filter dismissed + urut deadline)
-- dan pencarian baris usang saat sync.
create index if not exists tasks_active_deadline_idx
    on public.tasks (deadline)
    where dismissed_at is null;

create index if not exists tasks_source_idx
    on public.tasks (source);


-- =========================================================
--  DARI MIGRASI: 20261103000000_normalize_task_status.sql
-- =========================================================

-- =========================================================
--  SAMAKAN KOSAKATA STATUS
--
--  Versi lama menyimpan status berbahasa Indonesia
--  ("Belum Dikerjakan", "Sedang Dikerjakan", "Selesai"),
--  sedangkan form hanya mengenal tiga nilai baku. Akibatnya
--  <select> pada modal edit tidak punya <option> yang cocok:
--  nilainya kosong, form required tidak bisa disubmit, dan
--  status lama tertimpa saat user menekan simpan.
--
--  Migrasi ini memetakan semua varian ke nilai baku, lalu
--  memasang CHECK constraint supaya nilai asing tidak bisa
--  masuk lagi (dari aplikasi maupun dari SQL manual).
--
--  Idempoten: baris yang sudah baku tidak tersentuh.
-- =========================================================

update public.tasks
   set status = case lower(trim(status))

                    when 'selesai'          then 'Completed'
                    when 'sudah selesai'    then 'Completed'
                    when 'completed'        then 'Completed'
                    when 'complete'         then 'Completed'
                    when 'done'             then 'Completed'

                    when 'sedang dikerjakan' then 'In Progress'
                    when 'dikerjakan'        then 'In Progress'
                    when 'in progress'       then 'In Progress'
                    when 'progress'          then 'In Progress'
                    when 'proses'            then 'In Progress'

                    when 'belum dikerjakan'  then 'Pending'
                    when 'belum'             then 'Pending'
                    when 'pending'           then 'Pending'
                    when 'todo'              then 'Pending'
                    when 'to do'             then 'Pending'
                    when 'baru'              then 'Pending'

                    else 'Pending'
                end
 where status is null
    or status not in ('Pending', 'In Progress', 'Completed');


-- Jaga invarian di level database: tiga nilai ini saja.
do $$
begin

    if not exists (
        select 1
          from pg_constraint
         where conname = 'tasks_status_check'
           and conrelid = 'public.tasks'::regclass
    ) then

        alter table public.tasks
            add constraint tasks_status_check
            check (status in ('Pending', 'In Progress', 'Completed'));

    end if;

end
$$;


-- =========================================================
--  DARI MIGRASI: 20261104000000_enable_realtime.sql
-- =========================================================

-- =========================================================
--  AKTIFKAN REALTIME UNTUK TABEL TASKS
--
--  Aplikasi berlangganan perubahan tabel lewat WebSocket
--  (postgres_changes) supaya tugas yang ditambah/diubah/
--  dihapus teman langsung muncul tanpa reload.
--
--  Tanpa baris di publication ini, langganan tidak akan
--  pernah berbunyi — dan tidak memunculkan error apa pun,
--  sehingga sangat sulit didiagnosis. Karena itu bagian ini
--  dibuat sebagai migrasi, bukan langkah manual yang mudah
--  terlupa.
--
--  Catatan: publication supabase_realtime hanya ada di
--  proyek Supabase. Bila migrasi ini dijalankan pada
--  Postgres biasa, blok di bawah dilewati tanpa gagal.
-- =========================================================

do $$
begin

    if not exists (
        select 1
          from pg_publication
         where pubname = 'supabase_realtime'
    ) then

        raise notice 'Publication supabase_realtime tidak ada; realtime dilewati.';
        return;

    end if;


    if not exists (
        select 1
          from pg_publication_tables
         where pubname = 'supabase_realtime'
           and schemaname = 'public'
           and tablename = 'tasks'
    ) then

        alter publication supabase_realtime
            add table public.tasks;

        raise notice 'Tabel tasks ditambahkan ke publication supabase_realtime.';

    else

        raise notice 'Tabel tasks sudah ada di publication supabase_realtime.';

    end if;

end
$$;


-- =========================================================
--  DARI MIGRASI: 20261105000000_sync_upsert_batch.sql
-- =========================================================

-- =========================================================
--  UPSERT BATCH UNTUK SINKRONISASI LMS
--
--  Masalah sebelumnya: sync melakukan satu request HTTP per
--  tugas (N+1). Untuk 40 tugas berarti 40 round-trip, lambat
--  dan tidak atomik — kalau request ke-20 gagal, database
--  tertinggal setengah jadi.
--
--  Fungsi ini menyelesaikan semuanya dalam SATU panggilan:
--    - tugas baru  -> INSERT dengan status 'Pending'
--    - tugas lama  -> UPDATE data dasar saja
--
--  Status pilihan user (Pending / In Progress / Completed)
--  dan dismissed_at SENGAJA tidak ikut di-update. Kalau
--  ikut, setiap sync akan mengembalikan tugas yang sudah
--  diselesaikan atau disembunyikan user.
--
--  Mengapa perlu fungsi database, bukan upsert biasa?
--  PostgREST hanya bisa "update semua kolom yang dikirim".
--  Kalau status ikut dikirim agar baris baru valid, sync
--  akan menimpa status lama. ON CONFLICT DO UPDATE di sini
--  memisahkan keduanya: INSERT memakai 'Pending', sedangkan
--  UPDATE tidak menyentuh kolom status sama sekali.
-- =========================================================

create or replace function public.sync_lms_tasks(rows jsonb)
returns table (created integer, updated integer)
language plpgsql
security invoker
as $$
declare
    item        jsonb;
    v_inserted  boolean;
    v_created   integer := 0;
    v_updated   integer := 0;
begin

    for item in select * from jsonb_array_elements(rows)
    loop

        insert into public.tasks (
            course,
            class_name,
            deadline,
            category,
            status,
            source,
            external_id,
            synced_at
        )
        values (
            item ->> 'course',
            item ->> 'class_name',
            (item ->> 'deadline')::date,
            item ->> 'category',
            -- Nilai baku eksplisit: default kolom DB masih
            -- 'Belum Dikerjakan' dan tidak boleh dipakai.
            'Pending',
            item ->> 'source',
            item ->> 'external_id',
            coalesce(
                (item ->> 'synced_at')::timestamptz,
                now()
            )
        )
        on conflict (source, external_id)
            where external_id is not null
        do update set
            course     = excluded.course,
            class_name = excluded.class_name,
            deadline   = excluded.deadline,
            category   = excluded.category,
            synced_at  = excluded.synced_at
            -- status dan dismissed_at TIDAK disentuh.
        returning (xmax = 0) into v_inserted;

        if v_inserted then
            v_created := v_created + 1;
        else
            v_updated := v_updated + 1;
        end if;

    end loop;

    return query select v_created, v_updated;

end;
$$;


-- Hanya boleh dipanggil dengan hak pemanggil (security invoker),
-- jadi aturan akses tabel tetap berlaku seperti biasa.
--
-- Role anon/authenticated hanya ada di Supabase. Di Postgres
-- biasa perintah GRANT akan gagal dan membatalkan seluruh
-- migrasi, jadi dijalankan hanya bila role-nya memang ada.
revoke all on function public.sync_lms_tasks(jsonb) from public;

do $$
begin

    if exists (select 1 from pg_roles where rolname = 'anon') then
        grant execute on function public.sync_lms_tasks(jsonb) to anon;
    end if;

    if exists (select 1 from pg_roles where rolname = 'authenticated') then
        grant execute on function public.sync_lms_tasks(jsonb) to authenticated;
    end if;

end
$$;


-- =========================================================
--  DARI MIGRASI: 20261106000000_status_default_pending.sql
-- =========================================================

-- =========================================================
--  SAMAKAN DEFAULT STATUS DI LEVEL KOLOM
--
--  Kolom status masih punya default lama 'Belum Dikerjakan'.
--  Aplikasi sekarang selalu mengirim status eksplisit, tapi
--  default yang salah tetap berbahaya: satu INSERT yang lupa
--  menyertakan status (dari SQL manual, atau kode lama) akan
--  langsung melanggar CHECK constraint dan gagal.
--
--  Setelah ini, default-nya 'Pending' sehingga aman.
-- =========================================================

alter table public.tasks
    alter column status set default 'Pending';


-- Pastikan tidak ada sisa nilai lama sebelum constraint aktif.
update public.tasks
   set status = 'Pending'
 where status is null
    or status not in ('Pending', 'In Progress', 'Completed');
