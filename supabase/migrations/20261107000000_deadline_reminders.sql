-- =========================================================
--  PENGINGAT DEADLINE VIA WHATSAPP (CallMeBot)
--  ---------------------------------------------------------
--  Tujuan: kirim chat WhatsApp otomatis saat deadline tugas
--  sudah dekat (H-3, H-1, dan hari H) pada jam tertentu.
--
--  KENAPA DI DATABASE, BUKAN DI FRONTEND
--  Situs ini statis dan TIDAK punya login; RLS sengaja
--  dimatikan. Nomor WhatsApp dan API key TIDAK BOLEH dikirim
--  ke browser karena siapa pun bisa membacanya. Karena itu:
--    - nomor + API key disimpan di Supabase Vault;
--    - pengiriman dilakukan oleh pg_cron (penjadwal) yang
--      memanggil pg_net (klien HTTP) langsung dari Postgres.
--  Frontend hanya boleh menulis konfigurasi dan membaca
--  nomor yang sudah disamarkan.
--
--  KENAPA CallMeBot
--  WhatsApp Cloud API resmi TIDAK gratis untuk pesan yang
--  kita mulai sendiri: template kategori "utility" selalu
--  ditagih (tarif Indonesia sekitar USD 0.0287/pesan) sejak
--  1 Oktober 2026. Kuota 1.000 pesan gratis/bulan hanya
--  berlaku untuk "service message", yaitu balasan dalam 24 jam
--  setelah user lebih dulu mengirim pesan — tidak bisa dipakai
--  untuk pengingat otomatis. CallMeBot adalah satu-satunya
--  jalur WhatsApp yang benar-benar gratis untuk pemakaian
--  pribadi. Konsekuensinya: tidak resmi, hanya bisa mengirim
--  ke nomor sendiri, satu arah, dan ada batas kirim harian.
--  Kalau suatu saat pindah ke Cloud API resmi, cukup ganti
--  badan fungsi kirim_deadline_reminder() di bawah.
--
--  Idempoten: aman dijalankan berulang.
-- =========================================================


-- =========================================================
--  1. EKSTENSI
--  pg_cron = penjadwal, pg_net = klien HTTP.
--  Kalau salah satu tidak tersedia (mis. proyek lokal tanpa
--  ekstensi), migrasi TIDAK gagal: tabel dan fungsi tetap
--  dibuat, hanya penjadwalannya yang dilewati.
-- =========================================================

do $$
begin

    begin
        create extension if not exists pg_cron;
    exception when others then
        raise notice 'pg_cron tidak bisa diaktifkan: %', sqlerrm;
    end;

    begin
        create extension if not exists pg_net;
    exception when others then
        raise notice 'pg_net tidak bisa diaktifkan: %', sqlerrm;
    end;

end
$$;


-- =========================================================
--  2. KONFIGURASI CHANNEL
--  Tabel satu baris (id selalu true) supaya tidak perlu
--  mencari "baris milik siapa". API key TIDAK ada di sini —
--  ia disimpan di Vault dengan nama 'callmebot_apikey'.
-- =========================================================

create table if not exists public.reminder_channel (

    id          boolean     primary key default true
                            check (id),

    -- Nomor tujuan, format internasional tanpa "+".
    -- Contoh: 6281234567890
    phone       text,

    enabled     boolean     not null default false,

    -- Hari sebelum deadline. 0 = hari H.
    days_before integer[]   not null default '{3,1,0}',

    -- Jam kirim dalam zona waktu di bawah (0-23).
    send_hour   integer     not null default 8
                            check (send_hour between 0 and 23),

    timezone    text        not null default 'Asia/Jakarta',

    updated_at  timestamptz not null default now()

);


alter table public.reminder_channel disable row level security;

insert into public.reminder_channel (id)
values (true)
on conflict (id) do nothing;


-- =========================================================
--  3. LOG PENGIRIMAN
--  Sekaligus penjaga anti-dobel: satu tugas hanya boleh
--  dikirimi satu pesan per offset hari. Kalau cron berjalan
--  dua kali (atau dua worker bersamaan), unique index di
--  bawah menolak baris kedua.
-- =========================================================

create table if not exists public.reminder_log (

    id          bigint generated by default as identity primary key,

    -- NULL = pesan uji (tidak terikat tugas tertentu).
    -- Baris uji memakai offset_days = -1.
    task_id     bigint
                references public.tasks (id) on delete cascade,

    offset_days integer not null,

    channel     text not null default 'whatsapp',

    -- queued  : sudah diserahkan ke pg_net
    -- sent    : gateway menjawab 2xx
    -- failed  : gateway menjawab non-2xx / tidak terjawab
    status      text not null default 'queued',

    detail      text,

    request_id  bigint,

    created_at  timestamptz not null default now(),

    unique (task_id, offset_days)

);


alter table public.reminder_log disable row level security;

-- Tabel dibuat dengan `if not exists`, jadi pada proyek yang
-- pernah menjalankan versi sebelumnya kolom task_id masih
-- NOT NULL. Longgarkan supaya baris uji (task_id NULL) bisa
-- dicatat.
alter table public.reminder_log
    alter column task_id drop not null;

create index if not exists reminder_log_created_idx
    on public.reminder_log (created_at desc);


-- Kalau deadline sebuah tugas diubah, log lama dihapus.
-- Tanpa ini, tugas yang sudah pernah diingatkan pada H-1 tidak
-- akan diingatkan lagi setelah deadlinenya digeser.
create or replace function public.tasks_clear_reminders_on_deadline_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin

    if new.deadline is distinct from old.deadline then

        delete from public.reminder_log where task_id = new.id;

    end if;

    return new;

end;
$$;


drop trigger if exists tasks_clear_reminders on public.tasks;

create trigger tasks_clear_reminders
    after update of deadline on public.tasks
    for each row
    execute function public.tasks_clear_reminders_on_deadline_change();


-- =========================================================
--  4. UTILITAS: PERCENT-ENCODE
--  CallMeBot menerima pesan lewat query string GET. Tanpa
--  encoding, tanda "&", "#", atau baris baru akan memotong
--  URL dan pesan sampai tidak utuh.
-- =========================================================

create or replace function public.url_encode(p_text text)
returns text
language plpgsql
immutable
as $$
declare
    result text := '';
    ch     text;
    i      integer;
begin

    if p_text is null then
        return '';
    end if;

    for i in 1 .. length(p_text) loop

        ch := substr(p_text, i, 1);

        if ch ~ '[A-Za-z0-9\-_.~]' then
            result := result || ch;
        else
            result := result || '%' || lpad(
                upper(to_hex(ascii(ch))),
                2,
                '0'
            );
        end if;

    end loop;

    return result;

end;
$$;


-- =========================================================
--  5. PENYUSUN PESAN
--  Dipisah supaya format pesan bisa diubah tanpa menyentuh
--  logika penjadwalan.
-- =========================================================

create or replace function public.format_deadline_message(
    p_course     text,
    p_class_name text,
    p_deadline   date,
    p_offset     integer
)
returns text
language plpgsql
immutable
as $$
declare
    judul  text;
    kelas  text;
    kapan  text;
    tanggal text;
begin

    judul := coalesce(nullif(trim(p_course), ''), 'Tugas');
    kelas := coalesce(nullif(trim(p_class_name), ''), '-');

    kapan := case p_offset
                 when 0 then 'HARI INI'
                 when 1 then 'BESOK'
                 else p_offset || ' HARI LAGI'
             end;

    tanggal := to_char(p_deadline, 'DD Mon YYYY');

    return 'DEADLINE ' || kapan || E'\n'
        || judul || E'\n'
        || kelas || E'\n'
        || 'Jatuh tempo: ' || tanggal || E'\n'
        || '(Ghost Task Matrix)';

end;
$$;


-- =========================================================
--  6. PENJADWAL UTAMA
--  Dipanggil pg_cron tiap jam. Fungsi sendiri yang memeriksa
--  apakah jam lokal sudah sama dengan send_hour, jadi cron
--  tidak perlu tahu zona waktu.
-- =========================================================

-- create or replace tidak bisa mengubah tipe kembalian fungsi yang
-- sudah ada, jadi versi lama dibuang lebih dulu. Drop ini aman:
-- fungsi tidak dirujuk view/trigger apa pun.
drop function if exists public.run_deadline_reminders(boolean);

create or replace function public.run_deadline_reminders(
    p_force boolean default false
)
returns table (
    -- Nama kolom hasil sengaja TIDAK sama dengan nama kolom
    -- reminder_log. Kalau memakai "task_id" / "offset_days",
    -- PL/pgSQL akan menganggap nama itu variabel dan klausa
    -- `on conflict (task_id, offset_days)` di bawah gagal dengan
    -- "column reference is ambiguous".
    tugas_id    bigint,
    sisa_hari   integer,
    hasil       text
)
language plpgsql
security definer
set search_path = public
as $$
declare
    cfg        public.reminder_channel%rowtype;
    api_key    text;
    local_now  timestamp;
    hari_ini   date;
    rec        record;
    pesan      text;
    req_id     bigint;
    url_target text;
begin

    select * into cfg
      from public.reminder_channel
     where id;

    if cfg is null then
        return;
    end if;

    if not cfg.enabled then
        return;
    end if;

    if coalesce(cfg.phone, '') = '' then
        return;
    end if;

    local_now := (now() at time zone cfg.timezone);
    hari_ini  := local_now::date;

    -- Penjaga jam: kecuali dipaksa manual dari dashboard.
    if not p_force and extract(hour from local_now)::int <> cfg.send_hour then
        return;
    end if;

    select decrypted_secret into api_key
      from vault.decrypted_secrets
     where name = 'callmebot_apikey'
     limit 1;

    if coalesce(api_key, '') = '' then
        return;
    end if;

    for rec in
        select t.id,
               t.course,
               t.class_name,
               t.deadline,
               (t.deadline - hari_ini) as sisa
          from public.tasks t
         where t.dismissed_at is null
           and t.status <> 'Completed'
           and (t.deadline - hari_ini) = any (cfg.days_before)
           and not exists (
                   select 1
                     from public.reminder_log l
                    where l.task_id = t.id
                      and l.offset_days = (t.deadline - hari_ini)
               )
         order by t.deadline, t.course
    loop

        pesan := public.format_deadline_message(
            rec.course,
            rec.class_name,
            rec.deadline,
            rec.sisa
        );

        url_target :=
            'https://api.callmebot.com/whatsapp.php'
            || '?phone=' || public.url_encode(cfg.phone)
            || '&apikey=' || public.url_encode(api_key)
            || '&text=' || public.url_encode(pesan);

        begin

            select net.http_get(url := url_target) into req_id;

        exception when others then

            -- pg_net tidak ada / gagal: catat sebagai failed,
            -- jangan sampai menggagalkan seluruh loop.
            insert into public.reminder_log
                (task_id, offset_days, status, detail)
            values
                (rec.id, rec.sisa, 'failed', sqlerrm)
            on conflict (task_id, offset_days) do nothing;

            tugas_id  := rec.id;
            sisa_hari := rec.sisa;
            hasil     := 'failed: ' || sqlerrm;
            return next;
            continue;

        end;

        insert into public.reminder_log
            (task_id, offset_days, status, detail, request_id)
        values
            (rec.id, rec.sisa, 'queued', pesan, req_id)
        on conflict (task_id, offset_days) do nothing;

        tugas_id  := rec.id;
        sisa_hari := rec.sisa;
        hasil     := 'queued';
        return next;

    end loop;

end;
$$;


-- Hanya penjadwal (postgres) yang boleh menjalankan ini.
revoke all on function public.run_deadline_reminders(boolean) from public;


-- =========================================================
--  7. SINKRONKAN STATUS DARI JAWABAN pg_net
--  pg_net menyimpan hasil panggilan HTTP di net._http_response.
--
--  PENTING: CallMeBot membalas HTTP 201 walaupun permintaannya
--  ditolak — pesan errornya ada di BODY ("ERROR: apikey can not
--  be empty..."). Jadi status 2xx saja tidak cukup untuk
--  menyimpulkan pesan terkirim; isi respons ikut diperiksa.
--  Tanpa ini, UI akan melaporkan "sent" untuk pesan yang
--  sebenarnya gagal.
-- =========================================================

create or replace function public.refresh_reminder_status()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
    jumlah integer := 0;
begin

    begin

        update public.reminder_log l
           set status = case
                            when r.status_code not between 200 and 299 then 'failed'
                            when coalesce(r.content, '') ~* '(^|\n)\s*ERROR' then 'failed'
                            else 'sent'
                        end,
               detail = case
                            when r.status_code not between 200 and 299 then
                                'HTTP ' || r.status_code || ': '
                                || left(coalesce(r.content, ''), 200)
                            when coalesce(r.content, '') ~* '(^|\n)\s*ERROR' then
                                left(regexp_replace(r.content, '<[^>]+>', '', 'g'), 200)
                            else l.detail
                        end
          from net._http_response r
         where r.id = l.request_id
           and l.request_id is not null
           and l.status = 'queued';

        get diagnostics jumlah = row_count;

    exception when others then
        -- net._http_response tidak ada (pg_net mati). Diamkan.
        jumlah := 0;
    end;

    return jumlah;

end;
$$;


-- =========================================================
--  8. API UNTUK FRONTEND
--  Nomor dikembalikan TERSAMARKAN. API key tidak pernah
--  keluar dari Vault — hanya ada di dalam fungsi pengirim.
-- =========================================================

create or replace function public.reminder_channel_get()
returns table (
    phone_masked   text,
    enabled        boolean,
    days_before    integer[],
    send_hour      integer,
    timezone       text,
    has_api_key    boolean,
    last_sent_at   timestamptz,
    last_status    text
)
language plpgsql
security definer
set search_path = public
as $$
declare
    cfg public.reminder_channel%rowtype;
begin

    select * into cfg from public.reminder_channel where id;

    if cfg is null then
        return;
    end if;

    phone_masked := case
        when coalesce(cfg.phone, '') = '' then null
        when length(cfg.phone) <= 4 then '****'
        else repeat('*', greatest(length(cfg.phone) - 4, 0))
             || right(cfg.phone, 4)
    end;

    enabled     := cfg.enabled;
    days_before := cfg.days_before;
    send_hour   := cfg.send_hour;
    timezone    := cfg.timezone;

    select exists (
        select 1 from vault.decrypted_secrets where name = 'callmebot_apikey'
    ) into has_api_key;

    select l.created_at, l.status
      into last_sent_at, last_status
      from public.reminder_log l
     order by l.created_at desc
     limit 1;

    return next;

end;
$$;


create or replace function public.reminder_channel_save(
    p_phone     text,
    p_api_key   text default null,
    p_enabled   boolean default true,
    p_days      integer[] default '{3,1,0}',
    p_hour      integer default 8
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
    nomor    text;
    nomor_lama text;
begin

    select phone into nomor_lama
      from public.reminder_channel where id;

    -- p_phone null berarti "pertahankan nomor yang sudah ada".
    -- Frontend mengirim null saat kolom input masih berisi nomor
    -- tersamarkan (*******7890), karena nilai bertanda bintang
    -- tidak boleh disimpan sebagai nomor sungguhan.
    if p_phone is null then

        if coalesce(nomor_lama, '') = '' then
            raise exception 'Nomor WhatsApp wajib diisi.';
        end if;

        nomor := nomor_lama;

    else

        -- Buang spasi, tanda "+", dan tanda hubung. CallMeBot
        -- meminta format internasional tanpa "+" dan tanpa "00".
        nomor := regexp_replace(p_phone, '[^0-9]', '', 'g');

        if nomor like '00%' then
            nomor := substr(nomor, 3);
        end if;

        if length(nomor) < 8 then
            raise exception 'Nomor tidak valid: minimal 8 digit.';
        end if;

    end if;

    insert into public.reminder_channel
        (id, phone, enabled, days_before, send_hour, updated_at)
    values
        (true, nomor, p_enabled, coalesce(p_days, '{3,1,0}'), p_hour, now())
    on conflict (id) do update
        set phone      = excluded.phone,
            enabled    = excluded.enabled,
            days_before = excluded.days_before,
            send_hour  = excluded.send_hour,
            updated_at = now();

    -- API key hanya ditulis kalau diisi. Mengosongkan kolom
    -- di UI berarti "jangan ubah", bukan "hapus".
    if coalesce(p_api_key, '') <> '' then

        delete from vault.secrets where name = 'callmebot_apikey';

        perform vault.create_secret(
            p_api_key,
            'callmebot_apikey',
            'API key CallMeBot untuk pengingat deadline'
        );

    end if;

    return true;

end;
$$;


-- Tombol uji: kirim satu pesan sekarang tanpa menunggu jadwal.
-- Hasilnya dicatat di reminder_log dengan task_id NULL dan
-- offset_days = -1 (baris uji), supaya UI bisa menampilkan
-- apakah gateway benar-benar menerima pesan.
create or replace function public.reminder_send_test()
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
    cfg     public.reminder_channel%rowtype;
    api_key text;
    pesan   text;
    req_id  bigint;
begin

    select * into cfg from public.reminder_channel where id;

    if cfg is null or coalesce(cfg.phone, '') = '' then
        return 'Nomor belum diisi.';
    end if;

    select decrypted_secret into api_key
      from vault.decrypted_secrets
     where name = 'callmebot_apikey'
     limit 1;

    if coalesce(api_key, '') = '' then
        return 'API key belum diisi.';
    end if;

    pesan := 'Pesan uji dari Ghost Task Matrix. Kalau Anda menerima ini, '
          || 'pengingat deadline sudah aktif.';

    begin

        select net.http_get(
            url := 'https://api.callmebot.com/whatsapp.php'
                || '?phone=' || public.url_encode(cfg.phone)
                || '&apikey=' || public.url_encode(api_key)
                || '&text=' || public.url_encode(pesan)
        ) into req_id;

    exception when others then
        return 'Gagal mengirim: ' || sqlerrm;
    end;

    -- Catat supaya refresh_reminder_status() bisa memperbarui
    -- hasilnya. Baris uji memakai task_id NULL (tidak terikat
    -- tugas), jadi unique (task_id, offset_days) tidak bentrok.
    insert into public.reminder_log
        (task_id, offset_days, status, detail, request_id)
    values
        (null, -1, 'queued', pesan, req_id);

    return 'Pesan uji dikirim. Cek WhatsApp Anda dalam beberapa detik.';

end;
$$;


-- =========================================================
--  8b. HAK AKSES
--  PENTING: run_deadline_reminders() dan refresh_reminder_status()
--  TIDAK boleh bisa dipanggil dari browser. Keduanya sudah
--  security definer dan memegang API key dari Vault; kalau anon
--  bisa memanggilnya, siapa pun yang menemukan URL + publishable
--  key bisa memicu pengiriman WhatsApp tanpa batas (spam ke nomor
--  pemilik proyek, dan berisiko nomor diblokir CallMeBot).
--  Hanya postgres / service_role yang boleh — yaitu pg_cron.
-- =========================================================

revoke all on function public.run_deadline_reminders(boolean)
    from public, anon, authenticated;

revoke all on function public.refresh_reminder_status()
    from public, anon, authenticated;

revoke all on function public.url_encode(text)
    from public, anon, authenticated;

revoke all on function public.format_deadline_message(text, text, date, integer)
    from public, anon, authenticated;

grant execute on function public.reminder_channel_get()      to anon, authenticated;
grant execute on function public.reminder_channel_save(text, text, boolean, integer[], integer)
    to anon, authenticated;
grant execute on function public.reminder_send_test()        to anon, authenticated;


-- =========================================================
--  9. PENJADWALAN
--  Dijalankan tiap jam. Fungsi pengirim yang memutuskan
--  apakah jam lokal sudah cocok, jadi tidak ada ketergantungan
--  pada zona waktu server.
-- =========================================================

do $$
declare
    job record;
begin

    if not exists (select 1 from pg_extension where extname = 'pg_cron') then
        raise notice 'pg_cron tidak aktif — pengingat tidak dijadwalkan.';
        return;
    end if;

    -- Hapus jadwal lama supaya tidak menumpuk saat migrasi
    -- dijalankan berulang. cron.unschedule(nama) melempar error
    -- bila job tidak ada, jadi dicari dulu lewat cron.job.
    for job in
        select jobid from cron.job where jobname = 'deadline-reminders'
    loop
        perform cron.unschedule(job.jobid);
    end loop;

    perform cron.schedule(
        'deadline-reminders',
        '0 * * * *',
        $cron$
            select public.refresh_reminder_status();
            select public.run_deadline_reminders();
        $cron$
    );

end
$$;
